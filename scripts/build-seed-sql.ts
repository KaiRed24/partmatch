/**
 * Generates supabase/seed.sql from data/catalogue.ts and data/orders.ts.
 * Usage: npx tsx scripts/build-seed-sql.ts   (reads DEMO_ORDER_EMAIL from .env if set)
 */
import "dotenv/config";
import { writeFileSync } from "node:fs";
import { CATALOGUE } from "../data/catalogue";
import { ORDERS } from "../data/orders";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (a?: readonly string[]) => (a && a.length ? `array[${a.map(q).join(",")}]::text[]` : "'{}'::text[]");
const email = process.env.DEMO_ORDER_EMAIL || "demo@example.com";

const codes = new Set(CATALOGUE.map((p) => p.code));
for (const p of CATALOGUE) {
  if (p.stock.replacement && !codes.has(p.stock.replacement)) throw new Error(`${p.code}: unknown replacement ${p.stock.replacement}`);
}
for (const o of ORDERS) if (!codes.has(o.product_code)) throw new Error(`${o.ref}: unknown product ${o.product_code}`);

const lines: string[] = [
  "-- GENERATED by scripts/build-seed-sql.ts from data/catalogue.ts. Edit the TS file, not this one.",
  "-- Prices, stock, customers and orders are fictional.",
  "begin;",
  "delete from notifications; delete from orders; delete from tickets; delete from identifications; delete from stock; delete from products;",
  "",
];

for (const p of CATALOGUE) {
  lines.push(
    `insert into products (product_code,name,category,brand,compatible_with,attributes,returnable,restocking_fee,description,price_gbp) values (` +
      [q(p.code), q(p.name), q(p.category), q(p.brand), arr(p.compatible_with), `${q(JSON.stringify(p.attributes))}::jsonb`,
        String(p.returnable ?? true), String(p.restocking_fee ?? false), q(p.description), p.price.toFixed(2)].join(",") +
      ");",
  );
}
lines.push("");
for (const p of CATALOGUE) {
  const lead = p.stock.lead_days == null ? "null" : String(p.stock.lead_days);
  const repl = p.stock.replacement ? `(select id from products where product_code=${q(p.stock.replacement)})` : "null";
  lines.push(
    `insert into stock (product_id,qty_on_hand,supplier_lead_days,replacement_product_id) select id,${p.stock.qty},${lead},${repl} from products where product_code=${q(p.code)};`,
  );
}
lines.push("");
for (const o of ORDERS) {
  lines.push(
    `insert into orders (order_ref,customer_name,customer_email,product_id,status,promised_date) select ${q(o.ref)},${q(o.customer)},${q(email)},id,${q(o.status)},current_date + ${o.promised_in_days} from products where product_code=${q(o.product_code)};`,
  );
}
lines.push("commit;", "");

writeFileSync("supabase/seed.sql", lines.join("\n"));

const inStock = CATALOGUE.filter((p) => p.stock.qty > 0).length;
const lead = CATALOGUE.filter((p) => p.stock.qty === 0 && p.stock.lead_days != null).length;
const disc = CATALOGUE.length - inStock - lead;
console.log(`Wrote supabase/seed.sql: ${CATALOGUE.length} products (${inStock} in stock, ${lead} supplier, ${disc} discontinued), ${ORDERS.length} orders → ${email}`);
